#!/usr/bin/env python3
"""Builds the static data files used by the PWA in docs/.

- docs/data/tariff.json : compact Oman Tariff 2026 (hierarchy descriptions de-duplicated)
- docs/js/strings.js    : en/ar strings converted from the iOS Localizable.strings

Run from the project root:  python3 tools/build_web_data.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "CustomsToolkit"
OUT = ROOT / "docs"


def build_tariff():
    src = json.loads((APP / "Resources/oman_tariff_2026.json").read_text(encoding="utf-8"))
    chapters, headings, subheadings = {}, {}, {}
    rows = []
    for r in src["records"]:
        code = r["normalizedCode"]
        ch, hd, sh = r.get("chapter") or code[:2], r.get("heading") or code[:4], code[:6]
        if r.get("chapterDescriptionArabic") or r.get("chapterDescriptionEnglish"):
            chapters.setdefault(ch, [r.get("chapterDescriptionArabic"), r.get("chapterDescriptionEnglish")])
        if r.get("headingDescriptionArabic") or r.get("headingDescriptionEnglish"):
            headings.setdefault(hd, [r.get("headingDescriptionArabic"), r.get("headingDescriptionEnglish")])
        sub = [r.get("subheadingDescriptionArabic"), r.get("subheadingDescriptionEnglish")]
        sub_key = None
        if any(sub):
            # The same 6-digit subheading can carry different labels; key by text to stay faithful.
            sub_key = sh + "|" + json.dumps(sub, ensure_ascii=False)
            subheadings.setdefault(sub_key, [len(subheadings), sub])
        rows.append([
            code,
            r.get("descriptionArabic"),
            r.get("descriptionEnglish"),
            r.get("dutyRate"),
            r.get("procedure"),
            [r.get("indIndicator"), r.get("eftaIndicator"), r.get("sgIndicator"), r.get("usaIndicator")],
            1 if r.get("status") == "prohibited" else 0,
            subheadings[sub_key][0] if sub_key else None,
            r.get("sourcePage"),
        ])
    meta = src["metadata"]
    out = {
        "meta": {k: meta.get(k) for k in ("country", "year", "source", "recordCount", "datasetVersion")},
        "chapters": chapters,
        "headings": headings,
        "subheadings": [v[1] for v in sorted(subheadings.values(), key=lambda v: v[0])],
        "rows": rows,
    }
    (OUT / "data").mkdir(parents=True, exist_ok=True)
    path = OUT / "data/tariff.json"
    path.write_text(json.dumps(out, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"tariff.json: {len(rows)} rows, {path.stat().st_size / 1e6:.1f} MB")


STRING_RE = re.compile(r'^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;', re.M)


def parse_strings(path):
    text = path.read_text(encoding="utf-8")
    return {k: v.replace('\\"', '"').replace("\\n", "\n") for k, v in STRING_RE.findall(text)}


def build_strings():
    res = APP / "Localization/Resources"
    data = {lang: parse_strings(res / f"{lang}.lproj/Localizable.strings") for lang in ("en", "ar")}
    js = "// Generated by tools/build_web_data.py from the iOS Localizable.strings — do not edit.\n"
    js += "export const STRINGS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
    (OUT / "js").mkdir(parents=True, exist_ok=True)
    (OUT / "js/strings.js").write_text(js, encoding="utf-8")
    print(f"strings.js: en={len(data['en'])} ar={len(data['ar'])}")


if __name__ == "__main__":
    build_tariff()
    build_strings()
